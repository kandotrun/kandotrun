// README.md template. Pure: profile + feeds in, Markdown out.
import type { FeedSnapshot, OssEntry, Profile } from "../contract/schema";
import { esc } from "../render/svg";
import { renderMedia } from "./media";
import { type FrameRef, type GeneratedName, generatedPath } from "./paths";

export interface ReadmeInput {
  profile: Profile;
  feeds: FeedSnapshot;
}

const FRAME_WIDTH = 266;

function picture(name: GeneratedName, alt: string, opts: { frame?: FrameRef; width?: string | number } = {}): string {
  const dark = generatedPath(name, "dark", opts.frame);
  const light = generatedPath(name, "light", opts.frame);
  return [
    "<picture>",
    `<source media="(prefers-color-scheme: dark)" srcset="${dark}">`,
    `<img src="${light}" alt="${esc(alt)}" width="${opts.width ?? "100%"}">`,
    "</picture>",
  ].join("");
}

function heading(title: string, sub: string): string {
  return `### ${title} <sub>${sub}</sub>`;
}

function ossLine(entry: OssEntry): string {
  const extra = entry.extra ? `（[${entry.extra.label}](${entry.extra.url})）` : "";
  return `- [${entry.name}](${entry.url}) — ${entry.summary}${extra}`;
}

/**
 * One centred paragraph of inline frames that wraps by itself: 3 per line in
 * github.com's 846 px column, 2 at 590-806 px, 1 on phones. Fixed rows of three
 * broke into 2 + 1 with an orphan frame at every mid width.
 */
function contactSheet(profile: Profile): string {
  const cells = profile.featured.map(
    (project, index) =>
      `<a href="${project.url}">${picture("frame", `${project.title} — ${project.summary}`, { frame: { index, id: project.id }, width: FRAME_WIDTH })}</a>`,
  );
  return `<p align="center">\n${cells.join("\n")}\n</p>`;
}

export function renderReadme({ profile, feeds }: ReadmeInput): string {
  const heroAlt = `${profile.name} — ${profile.roleLine} in ${profile.location}. 写真の上で AF 枠と検出ボックスが動くビューファインダー`;
  const media = renderMedia(feeds).trim();

  const sections = [
    "<!-- Generated by src/cli/build.ts from data/*.ts. Edit the data, not this file. -->",
    `<a href="${profile.website}">${picture("hero", heroAlt)}</a>`,
    profile.intro,
    [heading("NOW", "いまやっていること"), "", ...profile.now.map((item) => `- ${item}`)].join("\n"),
    [heading("CONTACT SHEET", "つくったもの"), "", contactSheet(profile)].join("\n"),
    [heading("HISTOGRAM", "使っている言語と活動量"), "", picture("stats", "使用言語の比率と直近 1 年の活動量")].join("\n"),
    [
      heading("CONTRIBUTION SCAN", "直近 1 年の草"),
      "",
      picture("contrib", "直近 1 年のコントリビューションをスキャンするアニメーション"),
    ].join("\n"),
    media ? [heading("MEDIA", "新しい記事と人気の動画"), "", media].join("\n") : "",
    profile.badges.length
      ? [
          heading("SENSORS", "センサー"),
          "",
          // One line: GitHub's API (gfm mode) turns a soft line break into <br>.
          profile.badges.map((b) => `<a href="${b.href}"><img src="${esc(b.src)}" alt="${esc(b.alt)}"></a>`).join(" "),
        ].join("\n")
      : "",
    [heading("WORK", "最近つくっているもの"), "", ...profile.recent.map((item) => `- ${item}`)].join("\n"),
    [
      heading("PRODUCTS", "プロダクト"),
      "",
      ...profile.products.map((p) => `- **${p.name}** — ${p.summary}${p.demo ? `（[Demo](${p.demo})）` : ""}`),
    ].join("\n"),
    [
      heading("OSS", "オープンソース"),
      ...profile.oss.flatMap((category) => ["", `#### ${category.title}`, "", ...category.entries.map(ossLine)]),
      "",
      "<details>",
      "<summary>アーカイブ済み</summary>",
      "",
      ...profile.archived.map(ossLine),
      "",
      "</details>",
    ].join("\n"),
  ];

  return `${sections.filter(Boolean).join("\n\n")}\n`;
}
