import { describe, expect, it } from "vitest";
import { profile } from "../../data/profile";
import type { FeedSnapshot } from "../../src/contract/schema";
import { generatedPath } from "../../src/readme/paths";
import { renderReadme } from "../../src/readme/render";

const feeds: FeedSnapshot = {
  fetchedAt: "2026-10-21T00:00:00.000Z",
  zenn: [
    {
      title: "AI生成HTMLを「信頼せず」に配信する",
      url: "https://zenn.dev/nixo/articles/abc",
      publishedAt: "2026-10-01T09:00:00.000Z",
    },
  ],
  youtube: [
    {
      id: "rRWcNvxJvfk",
      title: "90万円のDGX SparkでDeepSeek V4を動かした結論",
      url: "https://www.youtube.com/watch?v=rRWcNvxJvfk",
      thumbnail: "https://i.ytimg.com/vi/rRWcNvxJvfk/mqdefault.jpg",
      viewCount: 9539,
    },
  ],
};

const readme = renderReadme({ profile, feeds });

function pictureFor(name: Parameters<typeof generatedPath>[0], frame?: { index: number; id: string }) {
  const dark = generatedPath(name, "dark", frame);
  const light = generatedPath(name, "light", frame);
  return { dark, light };
}

describe("renderReadme", () => {
  it("says it is generated and ends with a newline", () => {
    expect(readme.startsWith("<!-- Generated by src/cli/build.ts")).toBe(true);
    expect(readme.endsWith("\n")).toBe(true);
  });

  it("shows the hero as a theme-aware <picture>", () => {
    const { dark, light } = pictureFor("hero");
    expect(readme).toContain(`<source media="(prefers-color-scheme: dark)" srcset="${dark}">`);
    expect(readme).toContain(`src="${light}"`);
    expect(readme).toMatch(/alt="Kan Ninomiya[^"]*"/);
  });

  it("links every featured project to its frame card in one wrapping contact sheet", () => {
    profile.featured.forEach((project, index) => {
      const { dark, light } = pictureFor("frame", { index, id: project.id });
      expect(readme).toContain(`<a href="${project.url}">`);
      expect(readme).toContain(`srcset="${dark}"`);
      expect(readme).toContain(`src="${light}"`);
    });
    // One paragraph that wraps by itself: 3 frames per line at 846 px, 2 at
    // 590-766 px, 1 on phones. Fixed rows of 3 broke into 2+1 at mid widths.
    const sheets = readme.match(/<p align="center">\n<a href=[\s\S]*?<\/p>/g) ?? [];
    expect(sheets).toHaveLength(1);
    expect(sheets[0]?.match(/<a href=/g)).toHaveLength(profile.featured.length);
  });

  it("includes the stats and contribution panels", () => {
    for (const name of ["stats", "contrib"] as const) {
      const { dark, light } = pictureFor(name);
      expect(readme).toContain(`srcset="${dark}"`);
      expect(readme).toContain(`src="${light}"`);
    }
  });

  it("includes the Zenn articles and popular YouTube videos under MEDIA", () => {
    expect(readme).toMatch(/^### MEDIA <sub>新しい記事と人気の動画<\/sub>$/m);
    expect(readme).toContain("https://zenn.dev/nixo/articles/abc");
    expect(readme).toContain("https://www.youtube.com/watch?v=rRWcNvxJvfk");
  });

  it("keeps the existing badges as links", () => {
    for (const badge of profile.badges) {
      expect(readme).toContain(`<a href="${badge.href}">`);
      expect(readme).toContain(badge.src.replace(/&/g, "&amp;"));
    }
  });

  it("puts the badges on one line: a soft line break would render as <br> in GitHub's gfm API mode", () => {
    const sensors = readme.slice(readme.indexOf("### SENSORS"), readme.indexOf("### WORK"));
    const lines = sensors.split("\n").filter((line) => line.includes("<img"));
    expect(lines).toHaveLength(1);
    expect(lines[0]?.match(/<a href=/g)).toHaveLength(profile.badges.length);
  });

  it("lists the intro, now, recent work, products and OSS", () => {
    expect(readme).toContain(profile.intro);
    for (const item of profile.now) expect(readme).toContain(`- ${item}`);
    for (const item of profile.recent) expect(readme).toContain(`- ${item}`);
    for (const product of profile.products) {
      expect(readme).toContain(product.name);
      if (product.demo) expect(readme).toContain(`(${product.demo})`);
    }
    for (const category of profile.oss) {
      expect(readme).toContain(category.title);
      for (const entry of category.entries) expect(readme).toContain(`[${entry.name}](${entry.url})`);
    }
  });

  it("links the hero to the website and has no LINKS section", () => {
    expect(readme).toContain(`<a href="${profile.website}"><picture>`);
    expect(readme).not.toMatch(/^### LINKS/m);
  });

  it("folds archived projects into <details>", () => {
    const details = readme.match(/<details>[\s\S]*?<\/details>/)?.[0] ?? "";
    for (const entry of profile.archived) expect(details).toContain(`[${entry.name}](${entry.url})`);
  });

  it("is deterministic", () => {
    expect(renderReadme({ profile, feeds })).toBe(readme);
  });
});
